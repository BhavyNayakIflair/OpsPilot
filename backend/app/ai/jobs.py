"""Compatibility facade for callers of the previous job-manager API."""

import asyncio
import json
import time
from typing import Any, AsyncIterator, Dict, Optional

from fastapi.encoders import jsonable_encoder
from sqlalchemy import select

from app.core.database import AsyncSessionLocal
from app.models.job import BackgroundJob
from app.services.job_service import complete, fail, set_progress, submit_job


def _legacy_state(job: BackgroundJob) -> Dict[str, Any]:
    return {
        "job_id": job.id,
        "status": job.status,
        "progress": job.progress,
        "message": job.message,
        "created_at": job.created_at.timestamp() if job.created_at else time.time(),
        "updated_at": job.updated_at.timestamp() if job.updated_at else time.time(),
        "meta": (job.input or {}).get("meta", {}),
        "result": job.result,
        "error": job.error_message,
    }


class JobManager:
    """Preserves the legacy job_manager methods over durable database state."""

    def __init__(self, prefix: str = "ai:job:"):
        self.prefix = prefix

    async def create_job(
        self,
        job_id: Optional[str] = None,
        meta: Optional[Dict[str, Any]] = None,
    ) -> str:
        metadata = meta or {}
        org_id = metadata.get("org_id")
        if not org_id:
            raise ValueError("org_id is required to create a persistent job")
        async with AsyncSessionLocal() as db:
            job, _ = await submit_job(
                db,
                org_id=org_id,
                user_id=metadata.get("user_id"),
                job_type=metadata.get("job_type", "quote_draft"),
                input_data={"meta": metadata},
                subject_type="lead" if metadata.get("lead_id") else None,
                subject_id=metadata.get("lead_id"),
                subject_label=metadata.get("subject_label"),
            )
            if job_id and job_id != job.id:
                raise ValueError("Persistent job IDs are generated by the database service")
            return job.id

    async def update_job(
        self,
        job_id: str,
        status: str,
        progress: int,
        message: str = "",
        result: Optional[Any] = None,
        error: Optional[str] = None,
    ) -> None:
        safe_result = jsonable_encoder(result) if result is not None else None
        async with AsyncSessionLocal() as db:
            if status == "completed":
                await complete(db, job_id, safe_result, message=message or "Job completed")
            elif status == "failed":
                await fail(db, job_id, "internal_error", "The operation failed. Please retry.")
            else:
                await set_progress(db, job_id, progress, message or "Job running")

    async def get_job(self, job_id: str) -> Optional[Dict[str, Any]]:
        async with AsyncSessionLocal() as db:
            job = await db.scalar(select(BackgroundJob).where(BackgroundJob.id == job_id))
            return _legacy_state(job) if job else None

    async def stream_job_events(
        self,
        job_id: str,
        poll_interval_seconds: float = 0.5,
    ) -> AsyncIterator[str]:
        """Stream legacy per-job events until a terminal state or disconnect."""
        last_version = -1
        last_ping = time.monotonic()
        while True:
            job = await self.get_job(job_id)
            if not job:
                yield f"event: error\ndata: {json.dumps({'error': 'Job not found'})}\n\n"
                return
            version = job.get("version", job.get("updated_at"))
            if version != last_version:
                event = "done" if job["status"] in ("completed", "failed", "cancelled") else "progress"
                yield f"event: {event}\ndata: {json.dumps(job)}\n\n"
                last_version = version
            if job["status"] in ("completed", "failed", "cancelled"):
                return
            if time.monotonic() - last_ping >= 15:
                yield ": ping\n\n"
                last_ping = time.monotonic()
            await asyncio.sleep(poll_interval_seconds)


job_manager = JobManager()
