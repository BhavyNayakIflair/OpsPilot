export function translate(
  locale: Locale,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : placeholder
  );
}

export function useTranslation() {
  const { user } = useAuth();
  const locale = user && supportedLocales.some((item) => item === user.locale) ? user.locale : 'en';
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  const t = useMemo(() => (key: TranslationKey, values?: Record<string, string | number>) =>
    translate(locale, key, values), [locale]);
  return { locale, t };
}
